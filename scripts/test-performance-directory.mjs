import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile('worker.js','utf8');
const app=(await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'))).default;
const items=Array.from({length:165},(_,i)=>({mt20id:'PF'+(700000+i),prfnm:'한글 공연 '+i,
  prfpdfrom:'2026.10.01',prfpdto:'2027.11.20',fcltynm:'공연장 '+i,genrenm:'연극',
  prfstate:i<80?'02':'01',area:'서울'}));
let fetches=0;
const env={ASSETS:{fetch:async()=>{fetches++;return Response.json({current:items.slice(0,80),upcoming:items.slice(80)});}}};
const get=path=>app.fetch(new Request('https://movoka.tcflick.com'+path),env);
const first=await get('/performances');
assert.equal(first.status,200);
assert.equal(first.headers.get('x-movoka-directory'),'crawlable-20261027');
let html=await first.text();
assert.match(html,/canonical" href="https:\/\/movoka\.tcflick\.com\/performances"/);
assert.match(html,/name="robots" content="index,follow"/);
assert.equal((html.match(/<li><a href="\/performance\/PF\d+"/g)||[]).length,80);
assert.match(html,/href="\/performances\?page=2"/);
const second=await get('/performances?page=2');
assert.equal(second.status,200);
html=await second.text();
assert.equal((html.match(/<li><a href="\/performance\/PF\d+"/g)||[]).length,80);
assert.match(html,/rel="prev" href="\/performances"/);
assert.match(html,/rel="next" href="\/performances\?page=3"/);
assert.match(html,/canonical" href="https:\/\/movoka\.tcflick\.com\/performances\?page=2"/);
const third=await get('/performances?page=3');
assert.equal(third.status,200);
html=await third.text();
assert.equal((html.match(/<li><a href="\/performance\/PF\d+"/g)||[]).length,5);
assert.equal((await get('/performances?page=4')).status,404);
assert.equal((await get('/performances?page=9999')).status,404);
assert.equal((await get('/performances?page=1')).status,301);
assert.equal((await get('/performances/')).status,301);
const detail=await get('/performance/PF700000');
assert.equal(detail.status,200);
assert.match(await detail.text(),/href="\/performances"/);
assert.equal(fetches,1,'Directory shares the Worker catalog cache');
const home=await readFile('public/index.html','utf8');
assert.match(home,/<a href="\/performances"/);
const wrangler=await readFile('wrangler.jsonc','utf8');
assert.match(wrangler,/"\/performances"/);
const sitemap=await readFile('scripts/generate-sitemap.mjs','utf8');
assert.match(sitemap,/directoryUrls/);
console.log('MOVOKA SEO discovery tests passed: 165 performances, three HTML pages, canonical, pagination and cache.');
